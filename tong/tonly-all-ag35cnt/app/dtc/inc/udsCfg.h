/*  摘要说明  :                                                                */
/*    本头文件集中定义与 UDS（Unified Diagnostic Services）项目相关的配置常量，     */
/*    包括 DID 有效载荷的最大长度、常用字段的标准长度上限（VIN、APN、域名等）。     */
/*                                                                              */
/*  设计要点  :                                                                */
/*    - 所有长度均采用固定宏定义，单位为字节；                                   */
/*    - 遵循 MISRA C:2012 的常量命名与类型约定，均带后缀 `u`；                     */
/*    - 仅定义常量，不包含可执行逻辑，便于移植与跨平台使用。                       */
/*                                                                              */
/*  使用约定  :                                                                */
/*    - 调用方在构造/校验 DID 数据时使用这些常量作为长度边界；                     */
/*    - 若协议/项目更新导致长度变化，应仅在本文件修改，保持集中管理；                 */
/*    - 字符串长度常量均为 **不含终止符 `'\0'` 的最大有效长度**，                    */
/*      除非特别注明（如 LEN_PORT_TXT 包含 '\0'）。                               */
/*                                                                              */
/*  变更记录  :                                                                */
/*    v1.0.0  初版                                                             */
/* ========================================================================== */

#ifndef UDS_CFG_H_
#define UDS_CFG_H_

/* ============================ DID 载荷上限 ================================ */
/* 单个 DID 的最大载荷字节数（含文本/二进制），全局统一限制。 */
#define UDS_MAX_DID_PAYLOAD    (256u)

/* ============================ 常用字段长度 ================================ */
#define LEN_TIME_BCD           (7u)    /* 时间字段长度 (YYYY(2)+MM+DD+hh+mm+ss)，BCD 编码 */
#define LEN_VIN                (17u)   /* 车辆识别码 VIN 长度 */
#define LEN_ASCII_14           (14u)   /* 最长 14 字节 ASCII 文本（如电话号码） */
#define LEN_ASCII_32           (32u)   /* 最长 32 字节 ASCII 文本 */
#define LEN_ASCII_50           (50u)   /* 最长 50 字节 ASCII 文本 */
#define LEN_ASCII_128          (128u)  /* 最长 128 字节 ASCII 文本 */
#define LEN_IPv4_STR           (15u)   /* IPv4 文本 "255.255.255.255"，共 15 字节 */
#define LEN_DOMAIN_MAX         (64u)   /* 域名最大长度 */
#define LEN_LOG_PATH_MAX       (128u)  /* 日志路径最大长度 */
#define LEN_APN_MAX            (64u)   /* APN 最大长度 */
#define LEN_PORT_TXT           (6u)    /* 端口号文本：最多 5 位数字 + 1 位 '\0' 终止符 */
#define LEN_BIG_KEY            (128u)  /* 大密钥字段长度（如证书公钥等） */

#endif /* UDS_CFG_H_ */
