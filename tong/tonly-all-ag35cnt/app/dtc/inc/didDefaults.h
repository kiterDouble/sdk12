/*  摘要说明  :                                                                */
/*    本头文件声明了 UDS DID 默认值获取接口。                                   */
/*    每个 DID 对应一个可选的静态默认值（常量缓冲区），用于数据库冷启动时         */
/*    初始化 DID 的 RAM 槽与持久化存储。                                        */
/*                                                                              */
/*  设计要点  :                                                                */
/*    - 默认值由 did_defaults.c 内部静态常量维护；                              */
/*    - *pp 始终指向只读静态数据，不得修改或释放；                               */
/*    - 若 DID 未定义默认值，调用方需使用全零或其他策略补齐；                     */
/*    - 与 uds_cfg.h / did_registry.c 保持一致性。                               */
/*                                                                              */
/*  使用约定  :                                                                */
/*    - 调用方在初始化阶段 (UdsStorageInit) 内部调用此函数；                      */
/*    - 获取失败 (返回 0) 时，上层应以最小长度全零填充；                          */
/*    - 获取成功 (返回 1) 时，上层可直接使用返回的只读缓冲区。                     */
/*                                                                              */
/*  变更记录  :                                                                */
/*    v1.0.0  初版                                                             */
/* ========================================================================== */

#ifndef DID_DEFAULTS_H
#define DID_DEFAULTS_H

/* ================================== 依赖 =================================== */
#include <stdint.h>   /* uint16_t / uint8_t */

/* ========================================================================== */
/*  函数名称  : DefaultGetByDid                                               */
/*  功能描述  : 根据 DID 查询其默认值（若存在）。                                */
/* -------------------------------------------------------------------------- */
/*  参数说明  :                                                                */
/*    did   [in]   - UDS 数据标识符 (Data Identifier)，16 位枚举；                */
/*    pp    [out]  - 指向默认值缓冲的只读指针输出；返回时若成功，*pp != NULL；     */
/*    plen  [out]  - 默认值长度（字节数）；仅在返回 1 时有效。                     */
/*                                                                              */
/*  返回值    :                                                                */
/*    1  - 找到默认值，*pp / *plen 已设置；                                     */
/*    0  - 无默认值，调用方需自行处理（如填零）；                                 */
/*                                                                              */
/*  前置条件  :                                                                */
/*    - did 必须在注册表 (did_registry.c) 中定义；                              */
/*    - pp 与 plen 不得为 NULL；                                                 */
/*                                                                              */
/*  后置条件  :                                                                */
/*    - 返回成功时，*pp 指向内部静态常量缓冲，调用方只读使用；                     */
/*    - 不得修改、释放或长期缓存该指针；                                          */
/*                                                                              */
/*  执行步骤  :                                                                */
/*    STEP1: 校验入参 did/pp/plen；                                              */
/*    STEP2: 在静态表中查找匹配的 DID；                                          */
/*    STEP3: 若找到，输出指针与长度并返回 1；                                    */
/*    STEP4: 若未找到，返回 0。                                                  */
/* ========================================================================== */
int DefaultGetByDid(uint16_t did, const uint8_t **pp, uint16_t *plen);

#endif /* DID_DEFAULTS_H */
